"""MEL's screen fonts: Terminus Bold (the console fonts' PSF, Debian's console-setup-linux) as a C header.

  tools/gen_mel_fonts.py [OUT.h]      (default firmware/gen/mel_fonts.h)

Monospaced, a bit a pixel, rows of (w + 7) / 8 bytes, the left pixel the top bit. F16 and F20 have ASCII
32..126; F24 only 32..95 (no lower case: the firmware shows it as upper case), to keep it small.
Terminus: (c) Dimitar Zhekov, SIL Open Font License 1.1 (assets/fonts/Terminus-LICENSE.txt).
"""
import gzip
import struct
import sys
from pathlib import Path

SRC = Path(__file__).resolve().parents[1]
DIR = Path("/usr/share/consolefonts")
FONTS = [("F16", "Lat15-TerminusBold16.psf.gz", 126), ("F20", "Lat15-TerminusBold20x10.psf.gz", 126),
         ("F24", "Lat15-TerminusBold24x12.psf.gz", 95)]


def psf(path):
    """{code point: rows (ints)}, w, h"""
    b = gzip.open(path).read()
    if b[:2] == b"\x36\x04":                    # PSF1: 8 wide
        mode, h = b[2], b[3]
        n, w, size, at = (512 if mode & 1 else 256), 8, b[3], 4
        glyphs = [b[at + i * size: at + (i + 1) * size] for i in range(n)]
        tab, sep, step = b[at + n * size:], 0xFFFF, 2
        has = mode & 2
    else:                                       # PSF2
        _, _, hdr, flags, n, size, h, w = struct.unpack("<IIIIIIII", b[:32])
        glyphs = [b[hdr + i * size: hdr + (i + 1) * size] for i in range(n)]
        tab, has = b[hdr + n * size:], flags & 1
    bpr = (w + 7) // 8
    rows = [[int.from_bytes(g[r * bpr:(r + 1) * bpr], "big") >> (bpr * 8 - w) for r in range(h)] for g in glyphs]
    cmap = {}
    if not has:
        return {i: rows[i] for i in range(min(n, 256))}, w, h
    if b[:2] == b"\x36\x04":
        k = i = 0
        while k < n and i + 1 < len(tab):
            u = tab[i] | tab[i + 1] << 8
            i += 2
            if u == 0xFFFF:
                k += 1
            elif u != 0xFFFE:
                cmap.setdefault(u, rows[k])
    else:
        k, i = 0, 0
        while k < n and i < len(tab):           # UTF-8 sequences, 0xFE starts a sequence, 0xFF ends a glyph
            c = tab[i]
            if c == 0xFF:
                k, i = k + 1, i + 1
                continue
            if c == 0xFE:
                while i < len(tab) and tab[i] != 0xFF:
                    i += 1
                continue
            ln = 1 if c < 0x80 else 2 if c < 0xE0 else 3 if c < 0xF0 else 4
            cmap.setdefault(tab[i:i + ln].decode("utf-8", "replace"), rows[k])
            i += ln
        cmap = {ord(u): r for u, r in cmap.items() if len(u) == 1}
    return cmap, w, h


def main():
    out = Path(sys.argv[1]) if len(sys.argv) > 1 else SRC / "firmware" / "gen" / "mel_fonts.h"
    s = ["/* generated by tools/gen_mel_fonts.py: Terminus Bold, (c) Dimitar Zhekov, SIL OFL 1.1 */", "#pragma once",
         "#include <stdint.h>",
         "typedef struct {", "    uint8_t w, h, first, last;   /* monospaced; a bit a pixel, rows of (w + 7) / 8 bytes */",
         "    const uint8_t *data;", "} mel_font_t;"]
    for name, file, last in FONTS:
        cmap, w, h = psf(DIR / file)
        bpr = (w + 7) // 8
        data = []
        for ch in range(32, last + 1):
            for r in cmap.get(ch, cmap[ord("?")]):
                data += list((r << (bpr * 8 - w)).to_bytes(bpr, "big"))
        s.append(f"static const uint8_t {name}_DATA[{len(data)}] = {{")
        for i in range(0, len(data), 24):
            s.append("    " + ", ".join(f"0x{v:02x}" for v in data[i:i + 24]) + ",")
        s.append("};")
        s.append(f"static const mel_font_t {name} = {{{w}, {h}, 32, {last}, {name}_DATA}};")
        print(f"{name}: {file}, {w}x{h}, ASCII 32..{last}, {len(data)} B")
    out.write_text("\n".join(s) + "\n")


if __name__ == "__main__":
    main()
