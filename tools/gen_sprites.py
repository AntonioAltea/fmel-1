"""The drawn sprites (assets/sprites/*.png, pixel art at 1:1, transparent around) as a C header.

  tools/gen_sprites.py [OUT.h]        (default firmware/gen/mel_sprites.h)

A sprite is frames of the same size (SPRITES: the PNGs, in order) sharing one palette of up to 15 colours,
darkest first (colour 1, the outline, wins when the firmware shrinks it). A byte a pixel: the low nibble its
colour (0: clear), the high nibble its part. Part 0 is the drawing (the biggest blob of touching pixels); the
blobs apart from it (the choir's AAAAA) are parts 1..15 from left to right, so the firmware can bring them in
one by one. Each frame is stored run-length coded: (run 1..255, byte) pairs, row after row; a frame after the first
only where it is not the first (255: as the first there), so frames that hardly move cost little.
"""
import sys
from pathlib import Path

from PIL import Image

SRC = Path(__file__).resolve().parents[1]
SPRITES = {"choir": ["choir_idle", "choir"],   # frame 0: silent; 1: singing
           "flute": ["flute_idle", "flute_1", "flute_2"],   # 0: silent; 1, 2: playing
           "vibes": ["vibes_idle", "vibes_down", "vibes_1", "vibes_2"],   # 0: silent (mallets up); 1..3: playing
           "cello": ["cello_idle", "cello_1", "cello_2", "cello_3"],   # 0: silent (the bow up); 1..3: bowing
           "piano": ["piano_idle", "piano_1", "piano_2", "piano_3"],   # 0: silent (hands down); 1..3: playing
           "tape": ["tape_idle_1", "tape_idle_2"] + [f"tape_{k}" for k in range(1, 7)]}   # the cassette (TAPE), a snake
                                                       # its tape: 0, 1: stopped (its tongue); 2..7: running (its head round)


def blobs(px, w, h):
    seen, out = set(), []
    for y in range(h):
        for x in range(w):
            if px[y][x] is None or (x, y) in seen:
                continue
            todo, blob = [(x, y)], []
            seen.add((x, y))
            while todo:
                cx, cy = todo.pop()
                blob.append((cx, cy))
                for dx in (-1, 0, 1):
                    for dy in (-1, 0, 1):
                        nx, ny = cx + dx, cy + dy
                        if 0 <= nx < w and 0 <= ny < h and px[ny][nx] is not None and (nx, ny) not in seen:
                            seen.add((nx, ny))
                            todo.append((nx, ny))
            out.append(blob)
    return out


def load(name):
    im = Image.open(SRC / "assets" / "sprites" / f"{name}.png").convert("RGBA")
    w, h = im.size
    return w, h, [[None if im.getpixel((x, y))[3] < 128 else im.getpixel((x, y))[:3] for x in range(w)] for y in range(h)]


def frame(px, w, h, pal, name, base=None):
    bl = sorted(blobs(px, w, h), key=len, reverse=True)
    rest = sorted(bl[1:], key=lambda b: min(p[0] for p in b))
    if len(rest) > 15:
        raise SystemExit(f"{name}: {len(rest)} loose parts (15 at most)")
    part = {}
    for k, b in enumerate(rest):
        for p in b:
            part[p] = k + 1
    data = [0 if px[y][x] is None else part.get((x, y), 0) << 4 | (pal.index(px[y][x]) + 1)
            for y in range(h) for x in range(w)]
    if 255 in data:
        raise SystemExit(f"{name}: part 15 in colour 15 (255 means: as the first frame)")
    if base is not None:
        data = [255 if v == b else v for v, b in zip(data, base)]
    rle, i = [], 0
    while i < len(data):
        n = 1
        while i + n < len(data) and n < 255 and data[i + n] == data[i]:
            n += 1
        rle += [n, data[i]]
        i += n
    return len(rest), rle, data


def main():
    out = Path(sys.argv[1]) if len(sys.argv) > 1 else SRC / "firmware" / "gen" / "mel_sprites.h"
    s = ["/* generated by tools/gen_sprites.py from assets/sprites/ (PNG): frames run-length coded, (run, colour | part << 4);"
         " after the first, 255: as the first */",
         "#pragma once", "#include <stdint.h>", "typedef struct {", "    uint8_t w, h, nframes, parts;   /* parts: the last frame's */",
         "    uint16_t pal[16];               /* RGB565; [0] unused (clear) */", "    const uint8_t *const *frame;", "} sprite_t;"]
    most = 0
    for name, files in SPRITES.items():
        frames = [load(f) for f in files]
        w, h = frames[0][:2]
        if any(f[:2] != (w, h) for f in frames):
            raise SystemExit(f"{name}: its frames are not all {w}x{h}")
        pal = sorted({c for _, _, px in frames for row in px for c in row if c is not None}, key=lambda c: sum(c))
        if len(pal) > 15:
            raise SystemExit(f"{name}: {len(pal)} colours (15 at most)")
        total, first = 0, None
        for k, (f, (_, _, px)) in enumerate(zip(files, frames)):
            parts, rle, data = frame(px, w, h, pal, f, first)
            first = first or data
            total += len(rle)
            s.append(f"static const uint8_t SPR_{name.upper()}_{k}[{len(rle)}] = {{   /* {f}.png */")
            for i in range(0, len(rle), 32):
                s.append("    " + ",".join(str(v) for v in rle[i:i + 32]) + ",")
            s.append("};")
        lst = ", ".join(f"SPR_{name.upper()}_{k}" for k in range(len(files)))
        s.append(f"static const uint8_t *const SPR_{name.upper()}_FRAMES[{len(files)}] = {{{lst}}};")
        rgb = ", ".join(f"0x{(r >> 3) << 11 | (g >> 2) << 5 | b >> 3:04X}" for r, g, b in pal)
        s.append(f"static const sprite_t SPR_{name.upper()} = {{{w}, {h}, {len(files)}, {parts}, {{0, {rgb}}}, "
                 f"SPR_{name.upper()}_FRAMES}};")
        most = max(most, w * h)
        print(f"{name}: {w}x{h}, {len(files)} frames, {len(pal)} colours, {parts} loose parts, {total} B")
    s.append(f"#define SPR_MAXPX {most}u   /* the biggest frame, unpacked */")
    out.write_text("\n".join(s) + "\n")


if __name__ == "__main__":
    main()
