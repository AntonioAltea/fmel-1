"""The drawn sprites (assets/sprites/*.png, pixel art at 1:1, transparent around) as a C header.

  tools/gen_sprites.py [OUT.h]        (default firmware/gen/mel_sprites.h)

A byte a pixel: the low nibble its colour (0: clear, 1..15 the sprite's palette), the high nibble its
part. Part 0 is the drawing (the biggest blob of touching pixels); the blobs apart from it (the choir's
AAAAA) are parts 1..15 from left to right, so the firmware can bring them in one by one.
"""
import sys
from pathlib import Path

from PIL import Image

SRC = Path(__file__).resolve().parents[1]
SPRITES = ["choir"]


def blobs(px, w, h):
    seen, out = set(), []
    for y in range(h):
        for x in range(w):
            if px[y][x] is None or (x, y) in seen:
                continue
            todo, blob = [(x, y)], []
            seen.add((x, y))
            while todo:
                cx, cy = todo.pop()
                blob.append((cx, cy))
                for dx in (-1, 0, 1):
                    for dy in (-1, 0, 1):
                        nx, ny = cx + dx, cy + dy
                        if 0 <= nx < w and 0 <= ny < h and px[ny][nx] is not None and (nx, ny) not in seen:
                            seen.add((nx, ny))
                            todo.append((nx, ny))
            out.append(blob)
    return out


def sprite(name):
    im = Image.open(SRC / "assets" / "sprites" / f"{name}.png").convert("RGBA")
    w, h = im.size
    px = [[None if im.getpixel((x, y))[3] < 128 else im.getpixel((x, y))[:3] for x in range(w)] for y in range(h)]
    pal = sorted({c for row in px for c in row if c is not None}, key=lambda c: sum(c))
    if len(pal) > 15:
        raise SystemExit(f"{name}: {len(pal)} colours (15 at most)")
    bl = sorted(blobs(px, w, h), key=len, reverse=True)
    rest = sorted(bl[1:], key=lambda b: min(p[0] for p in b))
    if len(rest) > 15:
        raise SystemExit(f"{name}: {len(rest)} loose parts (15 at most)")
    part = {}
    for k, b in enumerate(rest):
        for p in b:
            part[p] = k + 1
    data = [0 if px[y][x] is None else part.get((x, y), 0) << 4 | (pal.index(px[y][x]) + 1)
            for y in range(h) for x in range(w)]
    return w, h, pal, len(rest), data


def main():
    out = Path(sys.argv[1]) if len(sys.argv) > 1 else SRC / "firmware" / "gen" / "mel_sprites.h"
    s = ["/* generated by tools/gen_sprites.py from assets/sprites/ (PNG): a byte a pixel, colour | part << 4 */",
         "#pragma once", "#include <stdint.h>", "typedef struct {", "    uint8_t w, h, parts;",
         "    uint16_t pal[16];          /* RGB565; [0] unused (clear) */", "    const uint8_t *px;", "} sprite_t;"]
    for name in SPRITES:
        w, h, pal, parts, data = sprite(name)
        s.append(f"static const uint8_t SPR_{name.upper()}_PX[{w * h}] = {{")
        for i in range(0, len(data), w):
            s.append("    " + ",".join(str(v) for v in data[i:i + w]) + ",")
        s.append("};")
        rgb = ", ".join(f"0x{(r >> 3) << 11 | (g >> 2) << 5 | b >> 3:04X}" for r, g, b in pal)
        s.append(f"static const sprite_t SPR_{name.upper()} = {{{w}, {h}, {parts}, {{0, {rgb}}}, SPR_{name.upper()}_PX}};")
        print(f"{name}: {w}x{h}, {len(pal)} colours, {parts} loose parts")
    out.write_text("\n".join(s) + "\n")


if __name__ == "__main__":
    main()
